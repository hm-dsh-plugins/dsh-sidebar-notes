/**
 * Build the plugin's two halves.
 *
 * The host half is plain ESM that Node loads directly, so it needs no bundling:
 * `src/index.js` is copied to `lib/index.js` with a banner saying where it came
 * from.
 *
 * The browser half must arrive as a `window.__ModuleLoader__.load({ id, factory })`
 * registration, which is what the web client's module system materializes.
 * That shape — not ESM, not an IIFE — is why this build exists at all: the
 * loader hands the factory one `require` bound to the platform module table,
 * so the bundle is emitted as CommonJS with React external and wrapped in the
 * registration by the banner and footer below.
 *
 * Usage:
 *   node scripts/build.mjs                 # both halves, unminified
 *   node scripts/build.mjs --client-only   # leave lib/index.js alone
 *   node scripts/build.mjs --minify        # smaller bundle, harder to read
 */

import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const clientOnly = process.argv.includes('--client-only')
const minify = process.argv.includes('--minify')

/** Package name registered with the client module system; also the bundle id. */
const ID = 'dsh-sidebar-notes'

/** Modules the platform seed table serves, so they must never be bundled in. */
const EXTERNAL = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']

/** First line of every generated file, so a reader lands on the source, not here. */
const GENERATED = '/* Generated from src/ by scripts/build.mjs — do not edit this file. */\n'

/** esbuild binary shipped by the `esbuild` package. */
function esbuildBin() {
  const name = process.platform === 'win32' ? 'esbuild.exe' : 'esbuild'
  const platform = `${process.platform}-${process.arch}`
  return join(root, 'node_modules', '@esbuild', platform, name)
}

/**
 * Emit one file, with the generated banner.
 * @param {string} path - absolute destination.
 * @param {string} content - file text.
 */
async function emit(path, content) {
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, GENERATED + content, 'utf8')
}

/** Build the browser bundle. */
async function buildClient() {
  const banner = [
    GENERATED.trimEnd(),
    `window.__ModuleLoader__.load({`,
    `\tid: ${JSON.stringify(ID)},`,
    `\tfactory: (require) => {`,
    `\t\tvar module = { exports: {} };`,
    `\t\tvar exports = module.exports;`,
    `\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });`,
  ].join('\n')

  const footer = [
    `\t\treturn module.exports;`,
    `\t}`,
    `});`,
  ].join('\n')

  const args = [
    join(root, 'src', 'client', 'index.js'),
    '--bundle',
    '--format=cjs',
    '--platform=browser',
    '--target=es2022',
    '--jsx=automatic',
    '--charset=utf8',
    '--log-level=warning',
    '--sourcemap',
    `--outfile=${join(root, 'lib', 'client.js')}`,
    `--banner:js=${banner}`,
    `--footer:js=${footer}`,
    '--define:process.env.NODE_ENV="production"',
    ...EXTERNAL.map((name) => `--external:${name}`),
  ]
  if (minify) args.push('--minify')

  const result = spawnSync(esbuildBin(), args, { stdio: 'inherit', cwd: root })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) throw new Error(`esbuild exited with ${String(result.status)}`)
}

/** Copy the host half into place, banner included. */
async function buildHost() {
  const entry = await readFile(join(root, 'src', 'index.js'), 'utf8')
  await emit(join(root, 'lib', 'index.js'), entry)

  // The host modules keep their relative layout, so `./host/route.js` in the
  // entry still resolves in `lib/`. The directory is replaced rather than merged
  // so a deleted module cannot linger in the build.
  await rm(join(root, 'lib', 'host'), { recursive: true, force: true })
  await cp(join(root, 'src', 'host'), join(root, 'lib', 'host'), { recursive: true })
  for (const name of await readdir(join(root, 'lib', 'host'))) {
    if (!name.endsWith('.js')) continue
    const path = join(root, 'lib', 'host', name)
    await writeFile(path, GENERATED + (await readFile(path, 'utf8')), 'utf8')
  }
}

// Clear only what this run regenerates. Wiping the whole directory would make
// `--client-only` take the host half with it, and `lib/index.js` is the
// package's `main` — the profile would lose the plugin, not just its build.
await rm(join(root, 'lib', 'client.js'), { force: true })
await rm(join(root, 'lib', 'client.js.map'), { force: true })
if (!clientOnly) await buildHost()
await buildClient()

const size = (await readFile(join(root, 'lib', 'client.js'))).length
const kib = `${Math.round(size / 1024)} KiB`
console.log(`built lib/client.js (${kib}${minify ? ', minified' : ''})${clientOnly ? '' : ' and lib/index.js'}`)
